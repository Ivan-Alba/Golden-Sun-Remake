public enum EquipmentSlot
{
    None,            // For non-equipable items
    Weapon,          // Swords, Axes, Maces, Staffs
    Shield,          // Shields, Armguards, Gloves
    Helmet,          // Helmets, Crowns, Caps
    Armor,           // Heavy Armors, Robes, Clothes
    Hands,           // Metal Bracelets, Armlets
    Boots,           // Boots, Greaves, Sandals
    Accessory,       // Rings, Charms
    PsynergyRelic    // Dedicated slots for Psynergy-granting artifacts
}