using System;
using System.Collections.Generic;
using UnityEngine;

/// <summary>
/// Subtype categorization defining exact equipment nature (e.g. Heavy Armor, Robe, Circlet, Heavy Helm, Shield, Glove).
/// Used by HeroEquipment to validate character equipment restrictions.
/// </summary>
public enum EquipmentSubtype
{
    // Body Armor Subtypes
    HeavyArmor,
    LightClothing,
    Robe,

    // Headgear Subtypes
    HeavyHelm,
    Hat,
    Circlet,
    Crown,

    // Arm/Hand Subtypes
    HeavyShield,
    Glove,
    Armlet,

    // Footwear & Accessories
    Boots,
    Ring,
    UnderShirt,

    // Weapon Subtypes (Extended in WeaponSO)
    Longsword,
    LightBlade,
    Axe,
    Mace,
    Staff,

    // Psynergy Relic default subtype (for PsynergyRelicSO)
    Relic
}

/// <summary>
/// ScriptableObject defining standard equipable items (Armor, Helms, Boots, Rings, Relics).
/// Holds stat modifiers, elemental power bonuses, subtype classification, cursed properties,
/// and zero-allocation stat extraction pipelines.
/// </summary>
[CreateAssetMenu(fileName = "Equipable_", menuName = "GoldenSun/Items/Equipable Standard")]
public class EquipableSO : ItemSO
{
    #region Equipment Slot & Categorization

    [Header("Equipment Slot & Subtype")]
    [Tooltip("Target body slot where this item is equipped.")]
    [SerializeField] private EquipmentSlot equipmentSlot = EquipmentSlot.Armor;

    [Tooltip("Specific subtype used for hero equipment compatibility checks (e.g. HeavyArmor vs Robe).")]
    [SerializeField] private EquipmentSubtype equipmentSubtype = EquipmentSubtype.HeavyArmor;

    [Tooltip("Unified list of fixed or percentage stat modifiers applied when equipped.")]
    [SerializeField] private List<StatBonus> statModifiers = new List<StatBonus>();

    #endregion

    #region Elemental Modifiers

    [Header("Elemental Modifiers")]
    [Tooltip("Elemental affinity of the equipment.")]
    [SerializeField] private ElementalType element = ElementalType.None;

    [Tooltip("Bonus added to elemental power or resistance when equipped.")]
    [SerializeField] private int elementalPowerBonus = 0;

    #endregion

    #region Golden Sun Special Mechanics

    [Header("Golden Sun Gear Mechanics")]
    [Tooltip("If true, this item is cursed. Equipping it locks the slot until cleansed at a Sanctum.")]
    [SerializeField] private bool isCursed = false;

    #endregion

    #region Active Item Use in Battle (Rings, Staffs)

    [Header("Active Item Use in Battle")]
    [Tooltip("Can this item be used directly as an action during turn-based combat?")]
    [SerializeField] private bool useInBattle = false;

    [Tooltip("Battle effect triggered when consuming or activating this item in combat.")]
    [SerializeField] private ItemBattleEffectSO battleUseEffect = null;

    #endregion

    #region Audio Settings

    [Header("Audio Settings")]
    [Tooltip("Optional custom audio clip played when equipping this item. If unassigned, uses fallback SFX.")]
    [SerializeField] private AudioClip equipSFX;

    [Tooltip("Fallback system SFX triggered when equipping if no custom clip is specified.")]
    [SerializeField] private SFXType fallbackEquipSFX = SFXType.UI_Equip;

    #endregion

    #region Public Properties

    public EquipmentSlot EquipmentSlot => equipmentSlot;
    public EquipmentSubtype EquipmentSubtype => equipmentSubtype;
    public IReadOnlyList<StatBonus> StatModifiers => statModifiers;
    public ElementalType Element => element;
    public int ElementalPowerBonus => elementalPowerBonus;

    public bool IsCursed => isCursed;

    public bool UseInBattle => useInBattle;
    public ItemBattleEffectSO BattleUseEffect => battleUseEffect;

    public AudioClip EquipSFX => equipSFX;
    public SFXType FallbackEquipSFX => fallbackEquipSFX;

    #endregion

    #region Zero-Allocation Stat Extraction API

    /// <summary>
    /// Populates a reusable container with StatModifiers generated by this equipment piece.
    /// Guarantees zero garbage collection allocations during equipment changes.
    /// </summary>
    public void GetStatModifiersNonAlloc(List<(StatType statType, StatModifier modifier)> resultsContainer)
    {
        if (resultsContainer == null) return;
        resultsContainer.Clear();

        if (statModifiers == null) return;

        for (int i = 0; i < statModifiers.Count; i++)
        {
            if (statModifiers[i] != null)
            {
                resultsContainer.Add((statModifiers[i].statType, statModifiers[i].ToStatModifier(this, isTemporary: false)));
            }
        }
    }

    /// <summary>
    /// Legacy allocation-based fallback method for extracting stat modifiers.
    /// Prefer using GetStatModifiersNonAlloc for performance-critical equipment swaps.
    /// </summary>
    public List<(StatType statType, StatModifier modifier)> GetStatModifiers()
    {
        var result = new List<(StatType, StatModifier)>();
        GetStatModifiersNonAlloc(result);
        return result;
    }

    #endregion
}