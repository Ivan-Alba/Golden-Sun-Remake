using System;
using System.Collections;
using System.Collections.Generic;
using UnityEngine;

public class HeroEquipment : MonoBehaviour
{
    private static int equipmentSlots = 7;
    private Equipable[] equippedItems;
    private FighterStats fighterStats;

    public static int EquipmentSlots { get => equipmentSlots; set => equipmentSlots = value; }
    public Equipable[] EquippedItems { get => equippedItems; set => equippedItems = value; }
    public static string[] SlotsName { get => slotsName; set => slotsName = value; }

    public enum SlotsIndex
    {
        WEAPON,
        SHIELD,
        HELMET,
        ARMOR,
        HANDS,
        BOOTS,
        SPECIAL
    }

    private static string[] slotsName = new string[] {
        "Weapon",
        "Shield",
        "Helmet",
        "Armor",
        "Hands",
        "Boots",
        "Accessory"
    };

    private void Awake()
    {
        EquippedItems = new Equipable[EquipmentSlots];
        fighterStats = GetComponent<FighterStats>();
    }

    public void SetEquipment(int slot, Equipable item)
    {
        if (item == null || slot < 0 || slot >= EquipmentSlots) return;

        // 1. Remove existing item in that slot if present
        if (EquippedItems[slot] != null)
        {
            RemoveEquipment(slot);
        }

        // 2. Remove item from inventory
        if (InventoryController.Instance != null)
        {
            InventoryController.Instance.LoseItem(item.ItemSlug, 1);
        }

        // 3. Assign new item to slot
        EquippedItems[slot] = item;

        // 4. Add Stat Modifiers to FighterStats using this item instance as Source
        if (fighterStats != null && item.StatName != null && item.StatValue != null)
        {
            for (int i = 0; i < item.StatName.Length; i++)
            {
                if (i < item.StatValue.Length && Enum.TryParse<StatType>(item.StatName[i], true, out StatType statType))
                {
                    StatModifier modifier = new StatModifier(
                        value: item.StatValue[i],
                        type: StatModifierType.Flat,
                        source: item,
                        isTemporary: false
                    );

                    fighterStats.AddStatModifier(statType, modifier);
                }
            }
        }
    }

    public void RemoveEquipment(int slot)
    {
        if (slot < 0 || slot >= EquipmentSlots) return;

        Equipable itemToRemove = EquippedItems[slot];

        if (itemToRemove != null)
        {
            // 1. Remove all modifiers generated by this specific item instance
            if (fighterStats != null)
            {
                fighterStats.RemoveModifiersFromSource(itemToRemove);
            }

            // 2. Return item to inventory
            if (InventoryController.Instance != null)
            {
                InventoryController.Instance.AddItem(itemToRemove.ItemSlug);
            }

            // 3. Clear slot
            EquippedItems[slot] = null;
        }
    }
}